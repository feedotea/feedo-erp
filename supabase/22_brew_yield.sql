-- 22_brew_yield.sql — 茶葉報廢改用「茶湯 ml」填
--
-- 老闆：「報廢通常算茶湯欸」。店員倒掉的是泡好的茶，不是乾茶葉 ——
-- 之前只能填公克，等於要他自己心算「480ml 的茶是幾克茶葉」，
-- 所以他填 480 又按 ml，被系統擋下來（而且擋的理由被手機工具列蓋住）。
--
-- 存一個「1g 茶葉泡得出幾 ml」就換得回去。成本表的泡出量是每 600g：
--   成本表的泡出量本來分兩種（24,000ml → 40 ml/g、15,000ml → 25 ml/g），
--   但老闆說實際上「都算 40ml」，所以全部設 40。倒掉 480ml ＝ 480 ÷ 40 ＝ 12g。
--
-- ⚠ 這跟配方裡的用量對不起來：比賽工法茶／茉莉綠茶／獅頭機採烏龍茶的配方
--   是按 25 ml/g 算的（純茶每杯 15.1579g）。如果真的都是 40，這三支每杯應該是
--   9.4737g（純茶）／6.3158g（奶茶），成本會降不少。還沒改，等老闆確認。
--
-- 只有茶葉有這個欄位；其他品項是 null，單位清單就不會出現 ml。
-- 2026-10-03 已在正式庫執行。可重複執行。
-- =====================================================================

alter table erp_items add column if not exists brew_ml_per_g numeric(8,2);

-- 2026-10-03 老闆：「都算 40ml」。本來按成本表泡出量分 40／25 兩種，
-- 現在統一 40（比賽工法茶、茉莉綠茶、獅頭機採烏龍茶原本是 25）。
update erp_items set brew_ml_per_g = 40, updated_at = now() where cat = '茶葉';

